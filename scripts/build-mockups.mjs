/* Inlines the shared engine into the mockups.

   The mockups are opened straight off disk, and browsers refuse ES module
   imports over file://. So the engine is concatenated into each page between
   markers rather than imported. That keeps ONE source of truth: edit
   src/engine/, run this, and every page moves together.

   `--check` verifies the inlined copy still matches the module. CI runs it, so
   a page can never quietly drift back onto its own ladder — which is exactly
   what check.html did before any of this existed.

   Astro will import the module properly and this script retires. Until then
   the marker block is GENERATED: never hand-edit between the markers. */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const MODULES = ['constants.mjs', 'advisories.mjs', 'fit.mjs', 'normalize.mjs'];
const START = '/* ENGINE:START — generated by scripts/build-mockups.mjs, do not edit */';
const END = '/* ENGINE:END */';
const DSTART = '/* CARRIERS:START — generated from data/carriers/, do not edit */';
const DEND = '/* CARRIERS:END */';
const PAGES = ['mockup/index.html', 'mockup/check.html', 'mockup/bag.html'];

/** ESM -> a single browser-safe block. Imports between our own modules are
 *  dropped because everything ends up in one scope; exports become plain
 *  declarations. No bundler, no dependency, no build cache to go stale. */
function inlineEngine() {
  const parts = MODULES.map((m) => {
    let src = readFileSync(new URL(`src/engine/${m}`, root), 'utf8');
    /* Reject anything the flattener cannot faithfully represent, rather than
       emitting a page that throws in a browser. A namespace import silently
       produced `defaults is not defined` once; now it fails the build. */
    if (/^import\s+\*\s+as\s/m.test(src)) {
      throw new Error(`${m}: namespace imports cannot be inlined — use plain named imports`);
    }
    const aliased = src.match(/^import\s*\{[^}]*\bas\b[^}]*\}/m);
    if (aliased) {
      throw new Error(`${m}: aliased imports cannot be inlined (${aliased[0].replace(/\s+/g, ' ')}) — the alias does not exist once modules share one scope`);
    }
    src = src
      .replace(/^import\s*\{[\s\S]*?\}\s*from\s+'[^']+';\s*$/gm, '')
      .replace(/^import\s+[\w$]+\s+from\s+'[^']+';\s*$/gm, '')
      .replace(/^export \* from '[^']+';\s*$/gm, '')
      .replace(/^export \{[^}]*\}\s*from\s*'[^']+';\s*$/gm, '')
      .replace(/^export const \{[^}]*\}\s*=\s*[^;]+;\s*$/gm, '')
      .replace(/^export (const|function|class|let) /gm, '$1 ')
      .replace(/^export \{[^}]*\};\s*$/gm, '');
    return `// ---- src/engine/${m} ----\n${src.trim()}`;
  });
  return `${START}\n${parts.join('\n\n')}\n\nconst ENGINE = createEngine();\n${END}`;
}

/* Carrier data comes from data/carriers/*.json and is projected into the terse
   shape the pages were written against. Same reason as the engine: the pages
   cannot fetch over file://, and two sources of carrier truth is the exact
   problem we just finished removing from the engine.

   The projection is lossy on purpose — the JSON holds provenance, evidence and
   verification fields the mockups have no use for. It is one-directional:
   edit the JSON, never the generated block. */
function inlineCarriers() {
  const dir = new URL('data/carriers/', root);
  const files = readdirSync(dir).filter((f) => f.endsWith('.json') && f !== '_index.json');
  const rows = files
    .map((f) => JSON.parse(readFileSync(new URL(f, dir))))
    .sort((a, b) => a.iata.localeCompare(b.iata))
    .map((c) => {
      const fares = {};
      for (const a of c.allowances.filter((x) => x.type === 'cabin')) {
        const chk = c.allowances.find((x) => x.type === 'checked' && x.fare_class === a.fare_class);
        fares[a.fare_class] = {
          d: a.max_cm, kg: a.max_kg,
          ovh: a.max_cm[0] >= 45 ? 1 : 0,
          chk: chk?.free_pieces ?? 0,
          note: a.note ?? '',
        };
      }
      return { c: c.iata, n: c.name, st: c.strictness.score,
               e: c.strictness.evidence?.[0]?.claim ?? '', f: fares };
    });
  return `${DSTART}\nconst AIR = ${JSON.stringify(rows, null, 1)};\n${DEND}`;
}

const block = inlineEngine();
const carriers = inlineCarriers();
const check = process.argv.includes('--check');
let drifted = 0, written = 0;

for (const page of PAGES) {
  const url = new URL(page, root);
  const html = readFileSync(url, 'utf8');
  let out = html, changed = false, stale = [];
  for (const [name, a, b, want] of [['engine', START, END, block], ['carriers', DSTART, DEND, carriers]]) {
    const s = out.indexOf(a), e = out.indexOf(b);
    if (s === -1 || e === -1) continue;                 // page doesn't use this block
    if (out.slice(s, e + b.length) === want) continue;  // already current
    stale.push(name);
    out = out.slice(0, s) + want + out.slice(e + b.length);
    changed = true;
  }
  if (out.indexOf(START) === -1) { console.log(`  SKIP  ${page} — no engine markers yet`); continue; }
  if (!changed) { console.log(`  ok    ${page}`); continue; }
  if (check) { console.log(`  DRIFT ${page} — ${stale.join(' and ')} out of date`); drifted++; continue; }
  writeFileSync(url, out);
  console.log(`  built ${page} (${stale.join(', ')})`);
  written++;
}

if (check && drifted) {
  console.log(`\n${drifted} page(s) out of date. Run: npm run build:mockups`);
  process.exit(1);
}
console.log(check ? '\nall pages match src/engine/' : `\n${written} page(s) rebuilt`);
